#!/usr/bin/env node
// Generates the StackChan firmware reaction table from the single reviewed
// catalog, so the server and the device always agree on reaction IDs.
// Usage: node scripts/robot-catalog-header.mjs > <firmware>/main/hal/board/v_reactions.h
import {ROBOT_REACTIONS,ROBOT_EYES,ROBOT_MOUTHS,ROBOT_EFFECTS,ROBOT_MOTIONS} from '../lab/robot/robot-catalog.mjs';

const enumName = name => name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
const enumBlock = (type, values) => `enum class ${type} : uint8_t {\n${values.map(v => `    ${enumName(v)},`).join('\n')}\n};`;
const quote = text => JSON.stringify(text);

console.log(`// GENERATED by v-voice scripts/robot-catalog-header.mjs from lab/robot/robot-catalog.mjs.
// Do not edit by hand; regenerate when the catalog changes.
#pragma once
#include <cstdint>
#include <cstring>

namespace v_robot {

${enumBlock('Eyes', ROBOT_EYES)}

${enumBlock('Mouth', ROBOT_MOUTHS)}

${enumBlock('Effect', ROBOT_EFFECTS)}

${enumBlock('Motion', ROBOT_MOTIONS)}

struct Reaction {
    const char* id;
    const char* label;
    Eyes eyes;
    Mouth mouth;
    Effect effect;
    Motion motion;
    uint16_t hold_ms;
    uint8_t energy;
};

inline constexpr Reaction kReactions[] = {
${ROBOT_REACTIONS.map(r => `    {${quote(r.id)}, ${quote(r.label)}, Eyes::${enumName(r.eyes)}, Mouth::${enumName(r.mouth)}, Effect::${enumName(r.effect)}, Motion::${enumName(r.motion)}, ${r.holdMs}, ${r.energy}},`).join('\n')}
};
inline constexpr int kReactionCount = ${ROBOT_REACTIONS.length};

inline const Reaction* FindReaction(const char* id) {
    if (!id) return nullptr;
    for (const auto& r : kReactions) if (std::strcmp(r.id, id) == 0) return &r;
    return nullptr;
}

}  // namespace v_robot`);
